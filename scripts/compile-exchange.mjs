#!/usr/bin/env node
/**
 * Compile contracts/HuntersExchange.sol with solc 0.8.26
 * (EVM paris, optimizer on — the SwapHelpers/lib precedent's
 * settings) and emit src/lib/exchangeBytecode.ts with the ABI
 * and creation bytecode the in-app deploy flow needs.
 * Run: node scripts/compile-exchange.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import solc from 'solc';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const src = readFileSync(ROOT + '/contracts/HuntersExchange.sol', 'utf8');

const input = {
  language: 'Solidity',
  sources: { 'HuntersExchange.sol': { content: src } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'paris',
    outputSelection: {
      '*': { '*': ['abi', 'evm.bytecode.object'] },
    },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors || []).filter((e) => e.severity === 'error');
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
for (const w of out.errors || []) {
  if (w.severity === 'warning') console.error('warning:', w.message);
}
const c = out.contracts['HuntersExchange.sol'].HuntersExchange;
const body =
  '/**\n' +
  ' * GENERATED by scripts/compile-exchange.mjs from\n' +
  ' * contracts/HuntersExchange.sol (solc 0.8.26, EVM paris,\n' +
  ' * optimizer 200 runs). Do not edit by hand — re-run the\n' +
  ' * script after changing the contract.\n' +
  ' */\n' +
  'export const EXCHANGE_ABI = ' +
  JSON.stringify(c.abi) +
  ' as const;\n\n' +
  'export const EXCHANGE_BYTECODE = ' +
  JSON.stringify('0x' + c.evm.bytecode.object) +
  ';\n';
writeFileSync(ROOT + '/src/lib/exchangeBytecode.ts', body);
console.log(
  'compiled HuntersExchange: runtime+creation bytecode bytes =',
  c.evm.bytecode.object.length / 2,
);

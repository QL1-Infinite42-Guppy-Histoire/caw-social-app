const STRINGS: Record<Lang, Dict> = {
  en: EN,
  ja: JA,
  zh: ZH,
  ko: KO,
  es: ES,
};

export function tr(key: StrKey, vars?: Record<string, string>): string {
  let s: string = STRINGS[current][key] || STRINGS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(v);
    }
  }
  return s;
}
